import { chromium } from './pw.mjs';
import { serve } from './serve.mjs';
const root = process.argv[2]; const out = process.argv[3];
const server = await serve(root, 8765);
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const logs = [];
page.on('console', (m) => logs.push(m.type() + ': ' + m.text()));
page.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
const t0 = Date.now();
await page.goto('http://127.0.0.1:8765/index.html');
await page.waitForFunction(() => window.__empireRushStarted === true, null, { timeout: 180000 });
console.log('STARTED ms', Date.now() - t0);
await page.waitForTimeout(8000);
await page.screenshot({ path: out });
const gl = await page.evaluate(() => { const c = document.createElement('canvas'); return !!c.getContext('webgl2'); });
console.log('WEBGL2', gl);
console.log(logs.filter((l) => !l.startsWith('log:')).slice(0, 30).join('\n'));
console.log('LOG_LINES', logs.length);
await browser.close(); server.close();
